#!/usr/bin/env node
/**
 * Bundles the repo-root legal documents, TERMS.md and PRIVACY_POLICY.md and
 * their French versions TERMS.fr.md and PRIVACY_POLICY.fr.md (a Quebec
 * requirement), into packages/shared/src/legal/documents.generated.ts, which
 * the web pages (/terms, /privacy, /terms/fr, /privacy/fr), the web /eua form
 * and the native legal modal all render (jits-s6mi.7, jits-rog5.8). The
 * Markdown files stay the single source of truth; bundling their text (rather
 * than reading the files at run time) keeps the web pages independent of
 * Vercel's file tracing and puts the same text in the mobile JS bundle.
 *
 * For each document it also records the title (the first H1), the effective
 * and last-updated dates (the "**Effective date:**" / "**Last updated:**"
 * lines, or "**Date d'entrée en vigueur :**" / "**Dernière mise à jour :**"
 * in French; the colon may sit inside or outside the bold) and a version: the
 * first 12 hex characters of the SHA-256 of the Markdown, so an acceptance
 * can record exactly which text was shown (jits-rog5.2).
 *
 * Line endings are normalised to LF before hashing and embedding (and
 * .gitattributes keeps the files LF), so the version never depends on the
 * checkout.
 *
 * Run after editing any of them:  npm run legal:sync
 * Check without writing:          node packages/shared/scripts/sync-legal-docs.mjs --check
 * `src/legal/documents.test.ts` fails while the generated module is stale.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..", "..");
const out = join(here, "..", "src", "legal", "documents.generated.ts");

const SOURCES = [
  { name: "TERMS_EN", file: "TERMS.md" },
  { name: "TERMS_FR", file: "TERMS.fr.md" },
  { name: "PRIVACY_EN", file: "PRIVACY_POLICY.md" },
  { name: "PRIVACY_FR", file: "PRIVACY_POLICY.fr.md" },
];

const EFFECTIVE = /^(?:Effective date|Date d['’]entrée en vigueur)$/i;
const UPDATED = /^(?:Last updated|Dernière mise à jour)$/i;

/** The value of a "**Label:** value" or "**Label: value**" line, or null. */
function labelled(markdown, labelRe) {
  for (const raw of markdown.split(/\r?\n/)) {
    const line = raw.replace(/\*\*/g, "").trim();
    const m = /^([^:]+?)[\s  ]*:[\s  ]*(.+)$/.exec(line);
    if (m && labelRe.test(m[1].trim())) return m[2].trim();
  }
  return null;
}

function meta(file, markdown) {
  const h1 = /^#\s+(.+)$/m.exec(markdown);
  const title = h1 ? h1[1].replace(/\*+/g, "").trim() : null;
  const effectiveDate = labelled(markdown, EFFECTIVE);
  const lastUpdated = labelled(markdown, UPDATED);
  for (const [field, value] of Object.entries({ title, effectiveDate, lastUpdated })) {
    if (!value) throw new Error(`${file}: no ${field} found`);
  }
  const version = createHash("sha256").update(markdown, "utf8").digest("hex").slice(0, 12);
  return { title, effectiveDate, lastUpdated, version };
}

const consts = SOURCES.map(({ name, file }) => {
  // LF only, so a CRLF checkout (Windows, core.autocrlf) bundles and hashes
  // the same text and the same version as everyone else.
  const markdown = readFileSync(join(repoRoot, file), "utf8").replace(/\r\n?/g, "\n");
  const m = meta(file, markdown);
  return `/** ${file} */
export const ${name}: LegalDocumentData = {
  source: ${JSON.stringify(file)},
  title: ${JSON.stringify(m.title)},
  effectiveDate: ${JSON.stringify(m.effectiveDate)},
  lastUpdated: ${JSON.stringify(m.lastUpdated)},
  version: ${JSON.stringify(m.version)},
  markdown: ${JSON.stringify(markdown)},
};
`;
});

const body = `// GENERATED by packages/shared/scripts/sync-legal-docs.mjs (npm run legal:sync)
// from the repo-root TERMS.md, TERMS.fr.md, PRIVACY_POLICY.md and
// PRIVACY_POLICY.fr.md. Do not edit by hand: edit the Markdown and re-run.
//
// One named constant per document so a bundler can drop the ones a page does
// not import (each is tens of kilobytes).
import type { LegalDocumentData } from "./types";

${consts.join("\n")}`;

const rel = relative(repoRoot, out);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== body) {
    console.error(`${rel} is stale: run npm run legal:sync`);
    process.exit(1);
  }
  console.log(`${rel} is up to date`);
} else {
  writeFileSync(out, body);
  console.log(`wrote ${rel}`);
}
