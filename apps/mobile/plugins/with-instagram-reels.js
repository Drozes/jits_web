const { withAndroidManifest, withInfoPlist } = require("expo/config-plugins");

/**
 * Platform declarations the Reels handoff needs to be VISIBLE at all
 * (jits-s6mi.2).
 *
 * Both halves of Meta's "Sharing to Reels" integration are invisible to the
 * app without a declaration, and both fail SILENTLY when it is missing,
 * which is the expensive part.
 *
 * iOS: `canOpenURL` answers only for schemes listed in
 * `LSApplicationQueriesSchemes`. Without `instagram-reels` there, the
 * availability check reports Instagram as not installed on a device where
 * it plainly is, and the user is routed to a fallback for no reason. (The
 * share itself does not depend on this: `modules/instagram-reels`'s Swift
 * half calls `open` and reads its completion handler rather than gating on
 * `canOpenURL`, precisely so a missing plist entry cannot break the
 * handoff. `instagram` is listed alongside it for the fallback rung.)
 *
 * Android: package visibility filtering (Android 11+, and this app targets
 * well past it) hides `com.instagram.android` from `queryIntentActivities`
 * and `resolveActivity` unless it is named in `<queries>`. Here the stakes
 * are higher than on iOS: the Kotlin half sends an EXPLICIT intent with
 * `setPackage(...)`, and an explicit intent at a package the app cannot see
 * throws `ActivityNotFoundException`. So on Android this declaration is
 * load-bearing for the share itself, not only for detection.
 *
 * WHY A CONFIG PLUGIN. `android/` and `ios/` are generated by prebuild;
 * hand-edits there are erased. This follows the existing local-plugin
 * precedent at `plugins/with-android-backup-rules.js`.
 *
 * THIS IS A NATIVE CONFIG CHANGE (an `app.json` `plugins` entry, an
 * Info.plist key and a manifest element). Per the workspace mobile-deploy
 * policy that means a TESTFLIGHT BUILD, not an OTA. An OTA cannot carry it
 * and will ship without it, silently.
 */

/** The Reels composer's URL scheme, opened by the iOS half of the module. */
const REELS_SCHEME = "instagram-reels";
/**
 * Plain Instagram. Listed so slice jits-s6mi.3 can tell "Instagram is
 * installed but too old for Reels" apart from "Instagram is not installed",
 * which are different messages to show a user.
 */
const INSTAGRAM_SCHEME = "instagram";
const QUERIED_SCHEMES = [REELS_SCHEME, INSTAGRAM_SCHEME];

/** The Instagram Android package, the target of the ADD_TO_REEL intent. */
const INSTAGRAM_PACKAGE = "com.instagram.android";

/**
 * The Info.plist half, as a pure function so it can be asserted without
 * running a prebuild (which needs a full Xcode toolchain).
 *
 * Additive and idempotent: prebuild runs repeatedly, and other plugins write
 * this same array. `@react-native-google-signin` and `expo-linking` are both
 * capable of putting entries here, so clobbering it would break sign-in in
 * a way that looks nothing like a Reels change.
 */
function addQueriedSchemes(infoPlist) {
  const existing = Array.isArray(infoPlist.LSApplicationQueriesSchemes)
    ? infoPlist.LSApplicationQueriesSchemes
    : [];
  const missing = QUERIED_SCHEMES.filter((scheme) => !existing.includes(scheme));
  if (missing.length === 0) return infoPlist;
  infoPlist.LSApplicationQueriesSchemes = [...existing, ...missing];
  return infoPlist;
}

/**
 * The AndroidManifest half, likewise pure.
 *
 * `<queries>` is a direct child of `<manifest>`, a sibling of
 * `<application>`, and the manifest may already carry `<queries>` blocks
 * merged in from libraries (`expo-file-system`, `expo-sharing` and
 * `expo-image-picker` each contribute one). So this appends a `<package>`
 * entry into the first existing block rather than replacing anything, and
 * does nothing when the entry is already there.
 */
function addInstagramPackageQuery(androidManifest) {
  const manifest = androidManifest.manifest;
  if (!Array.isArray(manifest.queries)) {
    manifest.queries = [];
  }
  const alreadyDeclared = manifest.queries.some((query) =>
    (query.package ?? []).some((entry) => entry?.$?.["android:name"] === INSTAGRAM_PACKAGE),
  );
  if (alreadyDeclared) return androidManifest;

  if (manifest.queries.length === 0) {
    manifest.queries.push({});
  }
  const block = manifest.queries[0];
  if (!Array.isArray(block.package)) {
    block.package = [];
  }
  block.package.push({ $: { "android:name": INSTAGRAM_PACKAGE } });
  return androidManifest;
}

function withReelsInfoPlist(config) {
  return withInfoPlist(config, (cfg) => {
    addQueriedSchemes(cfg.modResults);
    return cfg;
  });
}

function withReelsAndroidQueries(config) {
  return withAndroidManifest(config, (cfg) => {
    addInstagramPackageQuery(cfg.modResults);
    return cfg;
  });
}

module.exports = function withInstagramReels(config) {
  return withReelsAndroidQueries(withReelsInfoPlist(config));
};

// Exported for the unit test, which is the only place these can be checked
// without a prebuild and a full native toolchain.
module.exports.addQueriedSchemes = addQueriedSchemes;
module.exports.addInstagramPackageQuery = addInstagramPackageQuery;
module.exports.QUERIED_SCHEMES = QUERIED_SCHEMES;
module.exports.INSTAGRAM_PACKAGE = INSTAGRAM_PACKAGE;
