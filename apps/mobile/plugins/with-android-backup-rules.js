const fs = require("node:fs");
const path = require("node:path");
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require("expo/config-plugins");

/**
 * Keeps the parked match-recording directory out of Android's backups.
 *
 * WHY THIS IS NEEDED AT ALL. `Paths.document` maps to `context.filesDir` on
 * Android (`expo-file-system/android/.../FileSystemModule.kt:35-36`), and
 * Expo sets `android:allowBackup="true"` on every build
 * (`@expo/config-plugins/build/android/AllowBackup.js`, "Defaults to
 * true"). Auto Backup for Apps includes `filesDir` and is capped at 25 MB
 * per app, so a single parked 300-600 MB clip does not just get uploaded,
 * it makes the app's ENTIRE backup fail for as long as it sits there,
 * silently taking the user's preferences and device-to-device transfer with
 * it. That is a different failure from iOS (which would happily upload the
 * clip) but it is not a smaller one.
 *
 * WHY IT IS DECLARATIVE AND NOT A NATIVE CALL. Android has no per-file
 * equivalent of `NSURLIsExcludedFromBackupKey`. What is backed up is decided
 * by XML referenced from the manifest, so this is the only correct
 * mechanism. `android:allowBackup="false"` would also "work" and is wrong:
 * it throws away backup of the preferences and auth material the user
 * actually wants preserved.
 *
 * BOTH FILES ARE WRITTEN ON PURPOSE. `dataExtractionRules` governs API 31+
 * (cloud backup and D2D transfer, separately). `fullBackupContent` governs
 * API 23-30. A build that ships only one is unprotected on the other half
 * of the install base.
 *
 * SECURESTORE IS EXCLUDED TOO (jits-mafl.1). Because this plugin owns both
 * manifest attributes, expo-secure-store's own rules (which exclude its
 * prefs) never apply; `app.json` sets its `configureAndroidBackup: false` so
 * the two plugins do not fight. SecureStore's `SecureStore` shared prefs
 * hold values encrypted with an Android Keystore key, and the Keystore is
 * never backed up: restored onto a new device (or a reinstall) they cannot
 * be decrypted and the auth gate wedges. So every section excludes the
 * `sharedpref` file `SecureStore` (Android appends `.xml` for that domain),
 * the same rule expo-secure-store ships.
 *
 * NO <include>, ON PURPOSE. expo-secure-store's own XML pairs the exclude
 * with `<include domain="sharedpref" path="."/>`, but any <include> turns
 * the rules into an allowlist: everything not included (files, databases,
 * including AsyncStorage) would silently stop being backed up. Exclude-only
 * rules are valid and keep "back up everything except these".
 */

const DIRECTORY = "match-uploads";

/** expo-secure-store's SharedPreferences file name (SecureStoreModule.kt). */
const SECURE_STORE_PREFS = "SecureStore";

/** API 31+. Cloud backup and device-to-device transfer are separate here. */
const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-rules.js. Do not edit by hand. -->
<data-extraction-rules>
    <cloud-backup>
        <exclude domain="file" path="${DIRECTORY}/" />
        <exclude domain="sharedpref" path="${SECURE_STORE_PREFS}" />
    </cloud-backup>
    <device-transfer>
        <exclude domain="file" path="${DIRECTORY}/" />
        <exclude domain="sharedpref" path="${SECURE_STORE_PREFS}" />
    </device-transfer>
</data-extraction-rules>
`;

/** API 23-30. */
const FULL_BACKUP_CONTENT = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-rules.js. Do not edit by hand. -->
<full-backup-content>
    <exclude domain="file" path="${DIRECTORY}/" />
    <exclude domain="sharedpref" path="${SECURE_STORE_PREFS}" />
</full-backup-content>
`;

function withBackupRulesFiles(config) {
  return withDangerousMod(config, [
    "android",
    async (cfg) => {
      const resXml = path.join(
        cfg.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "res",
        "xml",
      );
      await fs.promises.mkdir(resXml, { recursive: true });
      await fs.promises.writeFile(
        path.join(resXml, "elo_data_extraction_rules.xml"),
        DATA_EXTRACTION_RULES,
        "utf8",
      );
      await fs.promises.writeFile(
        path.join(resXml, "elo_backup_rules.xml"),
        FULL_BACKUP_CONTENT,
        "utf8",
      );
      return cfg;
    },
  ]);
}

/**
 * The manifest half, as a pure function of the parsed manifest, so it can
 * be asserted without running a prebuild. A prebuild is the only other way
 * to see this, and it needs a full Android toolchain.
 */
function setBackupAttributes(androidManifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  application.$["android:dataExtractionRules"] = "@xml/elo_data_extraction_rules";
  application.$["android:fullBackupContent"] = "@xml/elo_backup_rules";
  return androidManifest;
}

function withBackupRulesManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    setBackupAttributes(cfg.modResults);
    return cfg;
  });
}

module.exports = function withAndroidBackupRules(config) {
  return withBackupRulesManifest(withBackupRulesFiles(config));
};

// Exported for the unit test, which is the only place the XML can be checked
// without running a prebuild.
module.exports.setBackupAttributes = setBackupAttributes;
module.exports.DATA_EXTRACTION_RULES = DATA_EXTRACTION_RULES;
module.exports.FULL_BACKUP_CONTENT = FULL_BACKUP_CONTENT;
module.exports.DIRECTORY = DIRECTORY;
module.exports.SECURE_STORE_PREFS = SECURE_STORE_PREFS;
