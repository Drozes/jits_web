#!/usr/bin/env node
/**
 * Copies the repo-root TERMS.md and PRIVACY_POLICY.md into
 * lib/legal/documents.generated.ts, which the public /terms and /privacy
 * pages render (jits-s6mi.7). The Markdown files stay the single source of
 * truth; bundling their text (rather than reading the files at request time)
 * keeps the pages independent of Vercel's file tracing outside apps/web.
 *
 * Run after editing either file:  node apps/web/scripts/sync-legal-docs.mjs
 * `lib/legal/documents.test.ts` fails while the generated module is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..", "..");
const out = join(here, "..", "lib", "legal", "documents.generated.ts");

const terms = readFileSync(join(repoRoot, "TERMS.md"), "utf8");
const privacy = readFileSync(join(repoRoot, "PRIVACY_POLICY.md"), "utf8");

const body = `// GENERATED by apps/web/scripts/sync-legal-docs.mjs from the repo-root
// TERMS.md and PRIVACY_POLICY.md. Do not edit by hand: edit the Markdown and
// re-run the script.

export const TERMS_MARKDOWN = ${JSON.stringify(terms)};

export const PRIVACY_MARKDOWN = ${JSON.stringify(privacy)};
`;

writeFileSync(out, body);
console.log(`wrote ${out}`);
